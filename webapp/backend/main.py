@asynccontextmanager
async def lifespan(app: FastAPI):
    """Create the shared Z9Client, the capabilities cache, and manage upload storage."""
    logger.info("Starting freeglaz backend")
    # Event-loop watchdog FIRST: if a sync call/deadlock freezes the loop
    # (grey freeze of 10/06 with no trace), it dumps the stacks of all threads.
    app.state.loop_watchdog = LoopWatchdog(_LOG_DIR / "freeglaz_stall.log")
    await app.state.loop_watchdog.start()
    # Z9 ANTI-HAMMERING guard: FREEGLAZ_DISABLE_Z9_SUBSCRIBERS=1 → NO contact with
    # the real Z9 (neither real client, nor subscribers). Set by the conftest → 100%
    # HERMETIC tests (zero request to 192.168.1.50). z9=None also naturally disables the
    # subscribers below. Outside tests: not set → normal behavior.
    if os.getenv("FREEGLAZ_DISABLE_Z9_SUBSCRIBERS") == "1":
        logger.info("FREEGLAZ_DISABLE_Z9_SUBSCRIBERS=1 → Z9 not contacted (hermetic tests)")
        app.state.z9 = None
    else:
        try:
            app.state.z9 = Z9Client.from_env()
            logger.info("Z9Client ready — host=%s", app.state.z9.host)
        except Z9Error as e:
            logger.error("Z9Client not configured: %s", e)
            app.state.z9 = None
    # Argyll CMS availability: resolved ONCE at startup (static per session).
    # NON-BLOCKING — the backend starts regardless; the profiling features simply
    # cannot run until Argyll is installed. Surfaced to the frontend (warning
    # banner) via app.state.argyll and the Status.argyll field.
    from lib.z9_client.argyll import check_argyll
    from webapp.backend.models import ArgyllStatus
    _argyll = check_argyll()
    app.state.argyll = ArgyllStatus(
        ok=_argyll["ok"], bin_ok=_argyll["bin_ok"],
        ref_ok=_argyll["ref_ok"], missing=_argyll["missing"],
        bin_dir=_argyll["bin_dir"], ref_dir=_argyll["ref_dir"],
    )
    if not _argyll["ok"]:
        logger.warning(
            "Argyll CMS incomplete — missing: %s. Profiling features disabled "
            "until fixed. %s",
            ", ".join(_argyll["missing"]), _argyll["install_hint"],
        )
    else:
        logger.info("Argyll CMS available — bin=%s ref=%s",
                    _argyll["bin_dir"], _argyll["ref_dir"])
    app.state.capabilities_cache = {}
    app.state.paper_icc_cache = {}
    app.state.job_store = JobStore()
    app.state.use_mock_print = os.getenv("FREEGLAZ_MOCK_PRINT") == "1"
    if app.state.use_mock_print:
        logger.warning("FREEGLAZ_MOCK_PRINT=1 → mock worker enabled (no send to the Z9)")
    file_storage.cleanup_old(max_age_hours=24)

    # Anti-orphan scan sessions: close any session left active by a previous run.
    # A scan runs in a background thread inside THIS process → a restart kills it,
    # so any non-terminal session on disk is stale by definition (would otherwise
    # block every future scan via the "only one active" lock).
    try:
        from webapp.backend.services import scan_session
        n_orphans = scan_session.cleanup_orphans()
        if n_orphans:
            logger.info("Closed %d orphan scan session(s) at boot", n_orphans)
    except Exception:  # noqa: BLE001 — never block startup on a cleanup failure
        logger.exception("scan session boot cleanup failed")

    # Start the Z9 events subscriber if the Z9 is configured. Must have
    # FINISHED its initial fetch (await start()) before the yield, otherwise
    # the first HTTP requests could get an empty snapshot.
    # (In tests, app.state.z9 is None → subscribers naturally not started.)
    if app.state.z9 is not None:
        sub = Z9StatusPollSubscriber(app.state.z9)
        try:
            await sub.start()
            app.state.z9_status_subscriber = sub
        except Exception:  # noqa: BLE001
            logger.exception("Z9StatusPollSubscriber start failed — SSE disabled")
            app.state.z9_status_subscriber = None
    else:
        app.state.z9_status_subscriber = None

    # Job queue subscriber (Phase 2). Non-blocking: start just launches
    # the task, the first tick happens after poll_interval. The initial
    # snapshot is empty until the 1st successful poll (~3 s) — acceptable
    # for the UI which will briefly show "Chargement...".
    if app.state.z9 is not None:
        jobs_sub = Z9JobsSubscriber(app.state.z9)
        try:
            await jobs_sub.start()
            app.state.z9_jobs_subscriber = jobs_sub
        except Exception:  # noqa: BLE001
            logger.exception("Z9JobsSubscriber start failed — /api/jobs renverra vide")
            app.state.z9_jobs_subscriber = None
    else:
        app.state.z9_jobs_subscriber = None

    yield

    # Shutdown: stop the subscribers BEFORE cancel_all of the jobs (the
    # subscribers don't touch files, but we keep a consistent order
    # — network services first, then local state, then files).
    if app.state.z9_jobs_subscriber is not None:
        await app.state.z9_jobs_subscriber.stop()
    if app.state.z9_status_subscriber is not None:
        await app.state.z9_status_subscriber.stop()
    # We cancel the running jobs BEFORE cleaning up files: the real worker
    # (5b) reads the sources at send time, so the order matters.
    await app.state.job_store.cancel_all()
    file_storage.cleanup_all()
    # Robustness 25/05/2026: cleanly close the keep-alive HTTP sessions
    # (REST + SOAP). Avoids zombie sessions that would retain state
    # (stale queue UUID, TLS cache, cookies) between 2 successive
    # backend startups.
    if app.state.z9 is not None:
        try:
            app.state.z9.close()
            logger.info("Z9Client HTTP sessions closed cleanly")
        except Exception as e:  # noqa: BLE001
            logger.warning("Z9Client close failed: %s", e)
    if getattr(app.state, "loop_watchdog", None) is not None:
        await app.state.loop_watchdog.stop()
    logger.info("Stopping freeglaz backend")


