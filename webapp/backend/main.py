# ─── Persistent file logging ────────────────────────────────────────
# The freeglaz backend often runs without an accessible terminal (launched
# via a macOS `.app`, or in the background with `freeglaz web`). Since stdout
# is invisible, we duplicate all logs into a rotating file that the user
# can read with ``tail -f webapp/data/freeglaz.log`` when debugging.
#
# Configuration:
# - Path: ``webapp/data/freeglaz.log`` (consistent with job_mapping.json
#   and job_previews/ which are also in webapp/data/).
# - Rotation: 10 MB max per file, keep 3 backups (~40 MB total).
# - Format: ISO timestamp + level + module + message.

_LOG_DIR = Path(__file__).resolve().parent.parent / "data"
LOG_FILE = _LOG_DIR / "freeglaz.log"


def _configure_file_logging() -> None:
    """Attach a RotatingFileHandler to the root logger.

    Idempotent (uses a marker on the root logger to avoid attaching
    twice if the module is reloaded by uvicorn --reload).
    """
    root = logging.getLogger()
    if getattr(root, "_freeglaz_file_handler_installed", False):
        return
    try:
        _LOG_DIR.mkdir(parents=True, exist_ok=True)
        handler = logging.handlers.RotatingFileHandler(
            LOG_FILE,
            maxBytes=10 * 1024 * 1024,
            backupCount=3,
            encoding="utf-8",
        )
        handler.setLevel(logging.INFO)
        handler.setFormatter(logging.Formatter(
            "%(asctime)s %(levelname)-7s %(name)s — %(message)s",
            datefmt="%Y-%m-%dT%H:%M:%S",
        ))
        root.addHandler(handler)
        root.setLevel(logging.INFO)
        root._freeglaz_file_handler_installed = True  # noqa: SLF001
    except OSError:
        # If we can't write to the folder (permissions, disk full), we
        # don't crash — the app keeps running with just the uvicorn
        # stdout logging.
        logging.getLogger(__name__).warning(
            "Logging fichier %s indisponible, fallback stdout uniquement",
            LOG_FILE,
        )


_configure_file_logging()

