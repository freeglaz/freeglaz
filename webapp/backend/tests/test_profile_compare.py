# ─── ANTI-REGRESSION: distinction of colorimetric contents ──────
#
# Bug reported on 31/05/2026 (false positive): 3 mirror Z9 profiles
# showed identical metrics in the compare modal. True
# cause: these 3 profiles share byte-for-byte the A2B0/B2A0/wtpt tags
# (only `desc` differs) → identical colorimetric content = same
# metrics (correct by construction).
#
# Guardrail: these tests prove that:
# 1) two profiles REALLY distinct in content (A vs B, different LUTs and
#    grids) give distinct metrics + distinct signatures
#    (the backend never "clones" between profiles);
# 2) the content signature does reflect the colorimetric content
#    (twice the same path → twice the same signature);
# 3) the duplicate group is correctly detected when it exists.


def test_compare_profiles_distinct_content_yields_distinct_metrics():
    """Two profiles distinct in content must give distinct
    metrics — this is the basic contract of the comparison.
    Bug 31/05: slipped through because no test
    verified the DISTINCTION between profiles."""
    out = compare_profiles([
        _RES_A,
        _RES_B,
    ])
    e0, e1 = out["profiles"]
    # distinct file_size (sanity check of input data)
    assert e0["file_size"] != e1["file_size"]
    # Distinct content signatures (proof that the LUT differs)
    assert e0["content_signature"]
    assert e1["content_signature"]
    assert e0["content_signature"] != e1["content_signature"]
    # Distinct WP Lab (at least one component differs)
    assert e0["whitepoint_lab"] != e1["whitepoint_lab"]
    # Distinct gamut volumes (at least one of the intents)
    g0 = e0["gamut"]
    g1 = e1["gamut"]
    if g0.get("status") == "ok" and g1.get("status") == "ok":
        assert g0.get("relative") != g1.get("relative")
    # And no duplicate group
    assert out["meta"]["has_duplicates"] is False
    assert out["meta"]["duplicate_signature_groups"] == []


def test_compare_profiles_identical_content_signals_duplicates():
    """Twice the same profile → same metrics (expected, not a
    bug) AND identical signature AND duplicate group reported."""
    path = _RES_A
    out = compare_profiles([path, path])
    e0, e1 = out["profiles"]
    # Same file → same scalar values (sanity)
    assert e0["file_size"] == e1["file_size"]
    assert e0["content_signature"] == e1["content_signature"]
    assert e0["whitepoint_lab"] == e1["whitepoint_lab"]
    # Duplicate detected and exposed for the UI
    assert out["meta"]["has_duplicates"] is True
    groups = out["meta"]["duplicate_signature_groups"]
    assert len(groups) == 1
    assert groups[0]["n_profiles"] == 2
    assert groups[0]["profile_indices"] == [0, 1]
    assert groups[0]["signature"] == e0["content_signature"]


def test_compare_profiles_content_signature_is_md5_hex16():
    """Expected form: 16 hex characters (truncated md5). Stable from one
    call to the next for the same content."""
    out_a = compare_profiles([
        _RES_A,
        _RES_B,
    ])
    out_b = compare_profiles([
        _RES_A,
        _RES_B,
    ])
    for e in out_a["profiles"] + out_b["profiles"]:
        sig = e["content_signature"]
        assert len(sig) == 16
        # Hex only
        int(sig, 16)
    # Deterministic
    assert out_a["profiles"][0]["content_signature"] \
        == out_b["profiles"][0]["content_signature"]
    assert out_a["profiles"][1]["content_signature"] \
        == out_b["profiles"][1]["content_signature"]


def test_compare_profiles_mixed_distinct_and_duplicate():
    """3 entries: twice A + once B. Reports a single
    duplicate group (the two A's) and leaves B isolated."""
    res_a = _RES_A
    res_b = _RES_B
    out = compare_profiles([res_a, res_b, res_a])
    sigs = [e["content_signature"] for e in out["profiles"]]
