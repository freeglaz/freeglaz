# ─── PCS XYZ: correct decoding of the LUT (LUT Structure regression) ──
#
# Historical bug: load_a2b_clut ALWAYS decoded the A2B0 nodes with the
# Lab formula. For a PCS XYZ (colprof -ax profiles), the nodes encode
# XYZ → aberrant "Lab" ranges (e.g. all-negative b*) and skewed
# curvature. The fix detects the PCS, applies the output curves, decodes
# XYZ then converts to Lab D50. Tested here on a synthetic XYZ mft2.


def _synth_mft2(pcs: bytes) -> bytes:
    import struct as _st
    g, ic, oc, n_in, n_out = 2, 3, 3, 2, 2
    header = bytearray(128)
    header[16:20] = b"RGB "
    header[20:24] = pcs
    header[36:40] = b"acsp"

    mft2 = bytearray()
    mft2 += b"mft2" + b"\x00\x00\x00\x00"
    mft2 += bytes([ic, oc, g, 0])
    for v in (65536, 0, 0, 0, 65536, 0, 0, 0, 65536):
        mft2 += _st.pack(">i", v)
    mft2 += _st.pack(">H", n_in) + _st.pack(">H", n_out)
    for _ in range(ic):
        mft2 += _st.pack(">HH", 0, 65535)
    # CLUT 2x2x2: black at node 0, D50 white at the last node, gray elsewhere.
    white = (31594, 32768, 27031)
    black = (200, 200, 200)
    mid = (16000, 16500, 13500)
    nodes = []
    for r in range(g):
        for gg in range(g):
            for bb in range(g):
                if (r, gg, bb) == (g - 1, g - 1, g - 1):
                    nodes.append(white)
                elif (r, gg, bb) == (0, 0, 0):
                    nodes.append(black)
                else:
                    nodes.append(mid)
    for node in nodes:
        mft2 += _st.pack(">HHH", *node)
    for _ in range(oc):
        mft2 += _st.pack(">HH", 0, 65535)

    tag_table_off = 128
    a2b0_off = tag_table_off + 4 + 12
    tag_table = _st.pack(">I", 1) + b"A2B0" + _st.pack(">II", a2b0_off, len(mft2))
    out = bytes(header) + tag_table + bytes(mft2)
    return out


def test_load_a2b_clut_xyz_pcs_decoded_as_lab(tmp_path):
    p = tmp_path / "synth_xyz.icc"
    p.write_bytes(_synth_mft2(b"XYZ "))
    g, L, a, b = curv.load_a2b_clut(p)
    assert g == 2
    # D50 white (last node) → L*≈100, a*≈0, b*≈0
    assert abs(L[-1, -1, -1] - 100.0) < 0.5
    assert abs(a[-1, -1, -1]) < 1.0
    assert abs(b[-1, -1, -1]) < 1.0
    # Black (node 0) → low L*
    assert L[0, 0, 0] < 20.0
    # Healthy ranges: L in [0..101], a/b in [-128..128] (NOT the all-negative
    # b* of the bug).
    assert 0 <= L.min() <= L.max() <= 101.0
    assert -128 <= a.min() <= a.max() <= 128
    assert -128 <= b.min() <= b.max() <= 128


def test_load_a2b_clut_xyz_vs_lab_branch_differ(tmp_path):
    """Same bytes, different PCS header → different decoding (proof that
    the XYZ branch is indeed taken and not ignored)."""
    raw = bytearray(_synth_mft2(b"XYZ "))
    px = tmp_path / "x.icc"
    px.write_bytes(bytes(raw))
    raw[20:24] = b"Lab "
    pl = tmp_path / "l.icc"
    pl.write_bytes(bytes(raw))
    _, Lx, ax, bx = curv.load_a2b_clut(px)
    _, Ll, al, bl = curv.load_a2b_clut(pl)
    # The XYZ path brings white back to L*100; the Lab path (raw formula on
    # XYZ bytes) does not.
    assert abs(Lx[-1, -1, -1] - 100.0) < 0.5
    assert abs(Ll[-1, -1, -1] - 100.0) > 5.0
