    assert sigs[0] != sigs[1]
    groups = out["meta"]["duplicate_signature_groups"]
    assert len(groups) == 1
    assert sorted(groups[0]["profile_indices"]) == [0, 2]
    assert groups[0]["n_profiles"] == 2
    assert out["meta"]["has_duplicates"] is True


